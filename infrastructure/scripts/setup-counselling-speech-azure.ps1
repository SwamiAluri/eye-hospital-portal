<#
.SYNOPSIS
    Provision/verify Azure Speech infrastructure for Hospital Portal
    counselling recording transcription.

.DESCRIPTION
    This script:

    1. Validates Azure CLI authentication.
    2. Selects the target subscription.
    3. Discovers the existing storage account.
    4. Verifies the existing session-audio container.
    5. Verifies the container is private.
    6. Discovers or creates the counselling Speech resource.
    7. Enables SYSTEM-ASSIGNED managed identity.
    8. Grants Storage Blob Data Reader to the Speech identity.
    9. Adds a specific Storage resource-instance network rule for Speech.
    10. Preserves existing storage firewall/IP/VNet rules.
    11. Performs verification.
    12. Outputs only non-secret configuration values.

    IMPORTANT:
    - No SAS is created.
    - No storage account key is created.
    - No public Blob access is enabled.
    - No existing storage account is recreated.
    - No existing session-audio container is recreated.
    - No counselling audio is submitted to Speech.
    - No transcript is generated by this script.
    - No real secret is written to source control.
#>

[CmdletBinding()]
param(
    [string]$SubscriptionId = "a56bb96d-59a1-4d13-be58-e4c9e3a189a3",

    [string]$ResourceGroupName = "hospital-portal-rg",

    [string]$StorageAccountName = "hospitalblobdev01",

    [string]$AudioContainerName = "session-audio",

    [string]$SpeechResourceName = "hospital-portal-counselling-speech",

    [switch]$CreateSpeechResource,

    [switch]$Apply,

    [switch]$SkipNetworkRule,

    [switch]$SkipRoleAssignment
)

$ErrorActionPreference = "Stop"

# ============================================================
# CONSTANTS
# ============================================================

$StorageBlobDataReaderRoleId =
    "2a2b9908-6ea1-4ae2-8e65-a410df84e7d1"

$SpeechKind = "SpeechServices"
$SpeechSku = "S0"

# ============================================================
# HELPERS
# ============================================================

function Write-Step {
    param([string]$Message)

    Write-Host ""
    Write-Host "============================================================" `
        -ForegroundColor DarkGray
    Write-Host $Message -ForegroundColor Cyan
    Write-Host "============================================================" `
        -ForegroundColor DarkGray
}

function Write-Info {
    param([string]$Message)

    Write-Host "[INFO] $Message" -ForegroundColor Gray
}

function Write-Ok {
    param([string]$Message)

    Write-Host "[OK]   $Message" -ForegroundColor Green
}

function Write-Warn {
    param([string]$Message)

    Write-Host "[WARN] $Message" -ForegroundColor Yellow
}

function Write-Fail {
    param([string]$Message)

    Write-Host "[FAIL] $Message" -ForegroundColor Red
}

function Get-AzOutputText {
    param($Output)

    $lines = foreach ($item in @($Output)) {
        $text = if ($item -is [System.Management.Automation.ErrorRecord]) { $item.ToString() } else { [string]$item }
        if ($text -match '^\s*WARNING:') { continue }
        if ($text -match 'AccountKey=|DefaultEndpointsProtocol=|sig=') {
            throw "Azure CLI returned a secret-like value. It was not printed."
        }
        $text
    }

    return ($lines -join "`n").Trim()
}

function Invoke-AzJson {
    param(
        [Parameter(Mandatory)]
        [string[]]$Arguments
    )

    $previousPreference = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $result = & az @Arguments --output json 2>&1
        $exitCode = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $previousPreference
    }

    if ($exitCode -ne 0) {
        throw (Get-AzOutputText -Output $result)
    }

    $text = Get-AzOutputText -Output $result
    if ([string]::IsNullOrWhiteSpace($text)) {
        return $null
    }

    return ($text | ConvertFrom-Json)
}

function Invoke-AzText {
    param(
        [Parameter(Mandatory)]
        [string[]]$Arguments
    )

    $previousPreference = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $result = & az @Arguments --output tsv 2>&1
        $exitCode = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $previousPreference
    }

    if ($exitCode -ne 0) {
        throw (Get-AzOutputText -Output $result)
    }

    return (Get-AzOutputText -Output $result)
}

function Test-AzCommand {
    $null = Get-Command az -ErrorAction SilentlyContinue

    if (-not $?) {
        throw "Azure CLI 'az' is not installed or is not available on PATH."
    }
}

# ============================================================
# 1. AZURE CLI
# ============================================================

Write-Step "1. Validate Azure CLI"

Test-AzCommand

Write-Ok "Azure CLI found."

# ============================================================
# 2. LOGIN
# ============================================================

Write-Step "2. Validate Azure login"

$account = $null

try {
    $account = Invoke-AzJson @("account", "show")
    $null = Invoke-AzText @(
        "account",
        "get-access-token",
        "--query",
        "expiresOn"
    )
}
catch {
    Write-Warn "Azure CLI is not authenticated."
    Write-Host ""
    Write-Host "Run:" -ForegroundColor Yellow
    Write-Host "  az login" -ForegroundColor White
    Write-Host ""

    throw "Azure login required."
}

if ($null -eq $account) {
    throw "Unable to determine current Azure account."
}

Write-Ok "Azure login is valid."

# ============================================================
# 3. SUBSCRIPTION
# ============================================================

Write-Step "3. Select subscription"

Invoke-AzText @(
    "account",
    "set",
    "--subscription",
    $SubscriptionId
) | Out-Null

$selectedSubscription = Invoke-AzJson @("account", "show")

if ($selectedSubscription.id -ne $SubscriptionId) {
    throw "Azure subscription selection failed."
}

Write-Ok "Subscription:"
Write-Host "  Name : $($selectedSubscription.name)"
Write-Host "  ID   : $($selectedSubscription.id)"

$TenantId = $selectedSubscription.tenantId

Write-Info "Tenant ID: $TenantId"

# ============================================================
# 4. RESOURCE GROUP
# ============================================================

Write-Step "4. Validate resource group"

$resourceGroup = Invoke-AzJson @(
    "group",
    "show",
    "--name",
    $ResourceGroupName
)

if ($null -eq $resourceGroup) {
    throw "Resource group '$ResourceGroupName' was not found."
}

Write-Ok "Resource group exists."
Write-Host "  Name     : $($resourceGroup.name)"
Write-Host "  Location : $($resourceGroup.location)"

# ============================================================
# 5. STORAGE ACCOUNT
# ============================================================

Write-Step "5. Discover existing storage account"

$storage = Invoke-AzJson @(
    "storage",
    "account",
    "show",
    "--resource-group",
    $ResourceGroupName,
    "--name",
    $StorageAccountName
)

if ($null -eq $storage) {
    throw "Storage account '$StorageAccountName' was not found."
}

$StorageResourceId = $storage.id
$StorageLocation = $storage.location

Write-Ok "Storage account found."
Write-Host "  Name     : $($storage.name)"
Write-Host "  Location : $StorageLocation"
Write-Host "  Resource : $StorageResourceId"

# ============================================================
# 6. STORAGE SECURITY
# ============================================================

Write-Step "6. Inspect storage security"

$allowBlobPublicAccess = $storage.allowBlobPublicAccess
$allowSharedKeyAccess = $storage.allowSharedKeyAccess
$minimumTlsVersion = $storage.minimumTlsVersion

Write-Host "  Public blob access : $allowBlobPublicAccess"
Write-Host "  Shared key access  : $allowSharedKeyAccess"
Write-Host "  Minimum TLS        : $minimumTlsVersion"

if ($allowBlobPublicAccess -eq $true) {
    Write-Warn "Account-level Blob public access is enabled."
    Write-Warn "This is retained because the account contains existing patient-photo functionality."
    Write-Warn "Storage account allows container-level public access, but this does not make session-audio public. The deployment will verify that session-audio itself remains private."
}
else {
    Write-Ok "Blob public access is disabled at the storage account."
}

if ($allowSharedKeyAccess -eq $true) {
    Write-Info "Shared Key access is enabled."
    Write-Info "No change will be made."
}
else {
    Write-Ok "Shared Key access is disabled."
}

# ============================================================
# 7. SESSION-AUDIO CONTAINER
# ============================================================

Write-Step "7. Validate session-audio container"

$containerUrl = "https://management.azure.com$StorageResourceId/blobServices/default/containers/${AudioContainerName}?api-version=2023-01-01"
$container = $null

try {
    $container = Invoke-AzJson @(
        "rest",
        "--method",
        "get",
        "--url",
        $containerUrl
    )
}
catch {
    throw "session-audio could not be verified. Deployment stopped. No infrastructure changes have been made."
}

if ($null -eq $container -or $container.name -ne $AudioContainerName) {
    throw "session-audio could not be verified. Deployment stopped. No infrastructure changes have been made."
}

$containerPublicAccess = [string]$container.properties.publicAccess
if ([string]::IsNullOrWhiteSpace($containerPublicAccess)) {
    $containerPublicAccess = [string]$container.publicAccess
}

if ($containerPublicAccess -eq "Blob" -or $containerPublicAccess -eq "Container") {
    throw "session-audio has anonymous public access enabled. Deployment stopped because counselling recordings must remain private."
}

if ($containerPublicAccess -and $containerPublicAccess -ne "None") {
    throw "session-audio has anonymous public access enabled. Deployment stopped because counselling recordings must remain private."
}

Write-Ok "session-audio exists."
Write-Ok "session-audio is PRIVATE."

# ============================================================
# 8. STORAGE NETWORK RULES
# ============================================================

Write-Step "8. Inspect storage networking"

$listedRules = Invoke-AzJson @(
    "storage",
    "account",
    "network-rule",
    "list",
    "--resource-group",
    $ResourceGroupName,
    "--account-name",
    $StorageAccountName
)

$networkRules = $storage.networkRuleSet
if (-not $networkRules) { $networkRules = $storage.properties.networkAcls }
if (-not $networkRules) { $networkRules = $listedRules }

Write-Host "  Default action : $($networkRules.defaultAction)"
Write-Host "  Bypass         : $($networkRules.bypass)"

if ($networkRules.ipRules) {
    Write-Host "  Existing IP rules : $($networkRules.ipRules.Count)"
}
else {
    Write-Host "  Existing IP rules : 0"
}

if ($networkRules.virtualNetworkRules) {
    Write-Host "  Existing VNet rules : $($networkRules.virtualNetworkRules.Count)"
}
else {
    Write-Host "  Existing VNet rules : 0"
}

if ($networkRules.resourceAccessRules) {
    Write-Host "  Existing resource rules : $($networkRules.resourceAccessRules.Count)"
}
else {
    Write-Host "  Existing resource rules : 0"
}

# ============================================================
# 9. DISCOVER EXISTING SPEECH RESOURCES
# ============================================================

Write-Step "9. Discover existing Speech resources"

$speechResources = @(
    Invoke-AzJson @(
        "cognitiveservices",
        "account",
        "list",
        "--resource-group",
        $ResourceGroupName
    ) | Where-Object {
        $_.kind -eq "Speech" -or
        $_.kind -eq "SpeechServices"
    }
)

if ($speechResources.Count -gt 0) {

    Write-Ok "Existing Speech resource(s) found: $($speechResources.Count)"

    foreach ($speechItem in $speechResources) {
        Write-Host ""
        Write-Host "  Name     : $($speechItem.name)"
        Write-Host "  Kind     : $($speechItem.kind)"
        Write-Host "  Location : $($speechItem.location)"
        Write-Host "  ID       : $($speechItem.id)"
    }

    if ($speechResources.Count -eq 1) {

        $SpeechResourceName = $speechResources[0].name

        Write-Ok "Using existing Speech resource: $SpeechResourceName"

    }
    else {

        $selectedSpeech = @($speechResources | Where-Object { $_.name -eq $SpeechResourceName })

        if ($selectedSpeech.Count -eq 1) {
            Write-Ok "Using requested Speech resource: $SpeechResourceName"
        }
        else {

            Write-Warn @"
Multiple Speech resources exist in '$ResourceGroupName'.

The script will NOT guess which one belongs to counselling.

Pass -SpeechResourceName explicitly.
"@

            throw "Multiple Speech resources require explicit selection."
        }
    }
}
else {

    Write-Info "No counselling Speech resource found."

    if (-not $Apply) {
        $ContainerResourceId = "$StorageResourceId/blobServices/default/containers/$AudioContainerName"

        Write-Info "Proposed resource creation:"
        Write-Host "       $SpeechResourceName"
        Write-Host "       Kind     : SpeechServices"
        Write-Host "       SKU      : S0"
        Write-Host "       Location : $StorageLocation"
        Write-Host "       Identity : System Assigned"

        Write-Info "Proposed RBAC:"
        Write-Host "       Storage Blob Data Reader"
        Write-Host "       scope: $AudioContainerName"
        Write-Host "       $ContainerResourceId"

        Write-Info "Proposed network rule:"
        Write-Host "       specific Speech resource instance"
        Write-Host "       Existing default action, bypass, IP rules, and VNet rules are preserved."

        Write-Host ""
        Write-Host "[DRY RUN] No Azure changes applied."
        Write-Host ""
        Write-Host "No counselling audio was submitted by this script."
        Write-Host "No transcript was generated by this script."
        exit 0
    }

    if (-not $CreateSpeechResource) {
        throw "Speech resource does not exist. Re-run with -CreateSpeechResource -Apply. No changes were made."
    }
}

# ============================================================
# 10. CREATE SPEECH RESOURCE
# ============================================================

if ($CreateSpeechResource -and $speechResources.Count -eq 0) {

    Write-Step "10. Create counselling Speech resource"

    Write-Host "The following resource will be created:"
    Write-Host ""
    Write-Host "  Name     : $SpeechResourceName"
    Write-Host "  Kind     : SpeechServices"
    Write-Host "  SKU      : S0"
    Write-Host "  Location : $StorageLocation"
    Write-Host "  Identity : System Assigned"
    Write-Host ""

    if (-not $Apply) {

        Write-Warn "DRY RUN: Speech resource will NOT be created."
        Write-Warn "Re-run with -Apply to make Azure changes."

        exit 0
    }

    $previousPreference = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        & az cognitiveservices account create `
            --name $SpeechResourceName `
            --resource-group $ResourceGroupName `
            --kind $SpeechKind `
            --sku $SpeechSku `
            --location $StorageLocation `
            --assign-identity `
            --yes `
            --subscription $SubscriptionId `
            --only-show-errors `
            --output none
        $createExit = $LASTEXITCODE
    }
    finally {
        $ErrorActionPreference = $previousPreference
    }

    if ($createExit -ne 0) {
        throw "Speech resource creation failed."
    }

    Write-Ok "Speech resource created."

    Start-Sleep -Seconds 10
}

# ============================================================
# 11. GET SPEECH RESOURCE
# ============================================================

Write-Step "11. Inspect Speech resource"

$speech = Invoke-AzJson @(
    "cognitiveservices",
    "account",
    "show",
    "--name",
    $SpeechResourceName,
    "--resource-group",
    $ResourceGroupName
)

if ($null -eq $speech) {
    throw "Speech resource '$SpeechResourceName' could not be found."
}

$SpeechResourceId = $speech.id
$SpeechLocation = $speech.location
$SpeechEndpoint = $speech.properties.endpoint
$SpeechPrincipalId = $speech.identity.principalId

Write-Ok "Speech resource found."
Write-Host "  Name     : $($speech.name)"
Write-Host "  Location : $SpeechLocation"
Write-Host "  Resource : $SpeechResourceId"

if ([string]::IsNullOrWhiteSpace($SpeechPrincipalId)) {
    throw "Speech resource does not have a system-assigned managed identity."
}

Write-Ok "System-assigned managed identity found."
Write-Host "  Principal ID : $SpeechPrincipalId"

# ============================================================
# 12. ROLE ASSIGNMENT
# ============================================================

$ContainerResourceId =
    "$StorageResourceId/blobServices/default/containers/$AudioContainerName"

Write-Step "12. Validate Storage Blob Data Reader"

$existingAssignments = @(
    Invoke-AzJson @(
        "role",
        "assignment",
        "list",
        "--assignee-object-id",
        $SpeechPrincipalId,
        "--scope",
        $ContainerResourceId
    )
)

$matchingAssignment = $existingAssignments |
    Where-Object {
        $_.roleDefinitionId -like "*$StorageBlobDataReaderRoleId" -and
        $_.scope -eq $ContainerResourceId
    }

if ($matchingAssignment) {

    Write-Ok "Storage Blob Data Reader already exists."
    Write-Host "  Scope: $ContainerResourceId"

}
elseif ($SkipRoleAssignment) {

    Write-Warn "Role assignment skipped by request."

}
else {

    Write-Warn "Storage Blob Data Reader is missing."

    if (-not $Apply) {

        Write-Warn "DRY RUN: role assignment will NOT be created."
        Write-Warn "Re-run with -Apply to create it."

    }
    else {

        $previousPreference = $ErrorActionPreference
        $ErrorActionPreference = "Continue"
        try {
            & az role assignment create `
                --assignee-object-id $SpeechPrincipalId `
                --assignee-principal-type ServicePrincipal `
                --role $StorageBlobDataReaderRoleId `
                --scope $ContainerResourceId `
                --only-show-errors `
                --output none
            $roleExit = $LASTEXITCODE
        }
        finally {
            $ErrorActionPreference = $previousPreference
        }

        if ($roleExit -ne 0) {
            throw @"
Failed to assign Storage Blob Data Reader.

Your Azure identity likely needs permission to create role assignments,
such as Owner or User Access Administrator at the required scope.
"@
        }

        Write-Ok "Storage Blob Data Reader assigned."
    }
}

# ============================================================
# 13. STORAGE RESOURCE INSTANCE NETWORK RULE
# ============================================================

Write-Step "13. Configure Speech resource-instance network access"

$resourceRules = @()

if ($networkRules.resourceAccessRules) {
    $resourceRules = @($networkRules.resourceAccessRules)
}

$existingSpeechRule = $resourceRules |
    Where-Object {
        $_.resourceId -eq $SpeechResourceId
    }

if ($existingSpeechRule) {

    Write-Ok "Speech resource-instance network rule already exists."

}
elseif ($SkipNetworkRule) {

    Write-Warn "Network rule skipped by request."

}
else {

    Write-Warn "Speech resource-instance network rule is missing."

    if (-not $Apply) {

        Write-Warn "DRY RUN: network rule will NOT be created."
        Write-Warn "Re-run with -Apply to create it."

    }
    else {

        $previousPreference = $ErrorActionPreference
        $ErrorActionPreference = "Continue"
        try {
            & az storage account network-rule add `
                --resource-group $ResourceGroupName `
                --account-name $StorageAccountName `
                --resource-id $SpeechResourceId `
                --tenant-id $TenantId `
                --only-show-errors `
                --output none
            $networkExit = $LASTEXITCODE
        }
        finally {
            $ErrorActionPreference = $previousPreference
        }

        if ($networkExit -ne 0) {
            throw "Failed to create Storage resource-instance network rule."
        }

        Write-Ok "Speech resource-instance network rule created."

        Write-Info "Waiting for Azure network rule propagation..."

        Start-Sleep -Seconds 15
    }
}

# ============================================================
# 14. FINAL VERIFICATION
# ============================================================

Write-Step "14. Final verification"

$storageAfter = Invoke-AzJson @(
    "storage",
    "account",
    "show",
    "--resource-group",
    $ResourceGroupName,
    "--name",
    $StorageAccountName
)

if ($storageAfter.allowBlobPublicAccess -eq $true) {
    Write-Warn "Account-level Blob public access remains enabled. session-audio is checked separately and must stay private."
}
else {
    Write-Ok "Blob public access remains disabled at the storage account."
}

$containerAfterUrl = "https://management.azure.com$($storageAfter.id)/blobServices/default/containers/${AudioContainerName}?api-version=2023-01-01"
$containerAfter = Invoke-AzJson @("rest", "--method", "get", "--url", $containerAfterUrl)
$containerAfterAccess = [string]$containerAfter.properties.publicAccess
if ([string]::IsNullOrWhiteSpace($containerAfterAccess)) { $containerAfterAccess = "None" }
if ($containerAfterAccess -ne "None") {
    throw "session-audio has anonymous public access enabled. Deployment stopped because counselling recordings must remain private."
}
Write-Ok "session-audio remains private."

$networkAfter = $storageAfter.networkRuleSet
if (-not $networkAfter) { $networkAfter = $storageAfter.properties.networkAcls }
if (-not $networkAfter) {
    $networkAfter = Invoke-AzJson @(
        "storage",
        "account",
        "network-rule",
        "list",
        "--resource-group",
        $ResourceGroupName,
        "--account-name",
        $StorageAccountName
    )
}

if ([string]$networkAfter.defaultAction -ne [string]$networkRules.defaultAction) {
    throw "Verification failed: storage default network action changed."
}

if ([string]$networkAfter.bypass -ne [string]$networkRules.bypass) {
    throw "Verification failed: storage network bypass changed."
}

$ipBefore = 0
$ipAfter = 0
$vnetBefore = 0
$vnetAfter = 0
if ($networkRules.ipRules) { $ipBefore = @($networkRules.ipRules).Count }
if ($networkAfter.ipRules) { $ipAfter = @($networkAfter.ipRules).Count }
if ($networkRules.virtualNetworkRules) { $vnetBefore = @($networkRules.virtualNetworkRules).Count }
if ($networkAfter.virtualNetworkRules) { $vnetAfter = @($networkAfter.virtualNetworkRules).Count }

if ($ipBefore -ne $ipAfter -or $vnetBefore -ne $vnetAfter) {
    throw "Verification failed: existing storage IP or VNet rules changed."
}

$speechRuleAfter = @(
    $networkAfter.resourceAccessRules
) | Where-Object {
    $_.resourceId -eq $SpeechResourceId
}

if (-not $speechRuleAfter) {

    if ($Apply -and -not $SkipNetworkRule) {
        throw "Verification failed: Speech resource-instance network rule is missing."
    }

    Write-Warn "Speech resource-instance network rule is not currently present."

}
else {

    Write-Ok "Speech resource-instance network rule verified."
}

$roleAfter = @(
    Invoke-AzJson @(
        "role",
        "assignment",
        "list",
        "--assignee-object-id",
        $SpeechPrincipalId,
        "--scope",
        $ContainerResourceId
    )
) | Where-Object {
    $_.roleDefinitionId -like "*$StorageBlobDataReaderRoleId" -and
    $_.scope -eq $ContainerResourceId
}

if (-not $roleAfter) {

    if ($Apply -and -not $SkipRoleAssignment) {
        throw "Verification failed: Storage Blob Data Reader assignment is missing."
    }

    Write-Warn "Storage Blob Data Reader assignment is not currently present."

}
else {

    Write-Ok "Storage Blob Data Reader assignment verified."
}

# ============================================================
# 15. OUTPUT SAFE CONFIGURATION
# ============================================================

Write-Step "15. Safe configuration output"

Write-Host ""
Write-Host "DO NOT copy secrets into source control." -ForegroundColor Yellow
Write-Host ""

Write-Host "SubscriptionId:"
Write-Host "  $SubscriptionId"

Write-Host ""
Write-Host "ResourceGroup:"
Write-Host "  $ResourceGroupName"

Write-Host ""
Write-Host "StorageAccountName:"
Write-Host "  $StorageAccountName"

Write-Host ""
Write-Host "AudioContainer:"
Write-Host "  $AudioContainerName"

Write-Host ""
Write-Host "SpeechResourceName:"
Write-Host "  $SpeechResourceName"

Write-Host ""
Write-Host "SpeechResourceId:"
Write-Host "  $SpeechResourceId"

Write-Host ""
Write-Host "SpeechEndpoint:"
Write-Host "  $SpeechEndpoint"

Write-Host ""
Write-Host "SpeechManagedIdentityPrincipalId:"
Write-Host "  $SpeechPrincipalId"

Write-Host ""
Write-Host "ContainerScope:"
Write-Host "  $ContainerResourceId"

Write-Host ""
Write-Host "Required Auth Service configuration:"
Write-Host ""
Write-Host "  AzureSpeech__TrustedBlobAccess=true"
Write-Host "  AzureSpeech__Endpoint=$SpeechEndpoint"
Write-Host "  AzureSpeech__StorageAccountName=$StorageAccountName"
Write-Host "  AzureSpeech__Key=<SECRET STORE VALUE>"
Write-Host ""

# ============================================================
# 16. FINAL RESULT
# ============================================================

if ($Apply) {

    Write-Ok "Counselling Speech infrastructure configuration completed."

    Write-Host ""
    Write-Host "NEXT:"
    Write-Host "1. Configure Auth Service environment variables."
    Write-Host "2. Restart Auth Service."
    Write-Host "3. Run transcription manual UAT."
    Write-Host "4. Do NOT start AI Summary yet."
}
else {

    Write-Warn "DRY RUN completed."
    Write-Host ""
    Write-Host "No Azure changes were applied."
    Write-Host ""
    Write-Host "If the discovered resources are correct, rerun with:"
    Write-Host ""
    Write-Host "  -Apply"
}

Write-Host ""
Write-Host "No counselling audio was submitted by this script."
Write-Host "No transcript was generated by this script."
