import type { OptometryExamDraftData } from './optometry-exam-types';

/** Collects all examination state from the exam page into a visit draft payload. */
export function buildExamDraftPayload(
  visitId: string,
  patientId: string,
  complaint: string | undefined,
  state: Record<string, unknown>,
): OptometryExamDraftData {
  return {
    version: 1,
    visitId,
    patientId,
    complaint,
    visualAcuityData: state.visualAcuity,
    refractionData: state.refraction,
    autoRefractionData: state.autoRefraction,
    keratometryData: state.keratometry,
    colorVisionData: state.colorVision,
    contrastSensitivityData: state.contrastSensitivity,
    tonometryData: state.tonometry,
    pachymetryData: state.pachymetry,
    visualFieldData: state.visualField,
    vaExtended: state.vaExtended,
    iopExtended: state.iopExtended,
    wetRetinoscopy: state.wetRetinoscopy,
    dryRetinoscopy: state.dryRetinoscopy,
    subjectiveRefraction: state.subjectiveRefraction,
    retinoscopyData: state.retinoscopy,
    pupilExam: state.pupilExam,
    anteriorSegment: state.anteriorSegment,
    posteriorSegment: state.posteriorSegment,
    fundusExam: state.fundusExam,
    vitreousExam: state.vitreousExam,
    peripheralRetinaExam: state.peripheralRetinaExam,
    currentMedications: state.currentMedications,
    prescriptionItems: state.prescriptionItems,
    clAssessment: state.clAssessment,
    clPrescription: state.clPrescription,
    clFitting: state.clFitting,
    clCornealHealth: state.clCornealHealth,
    clInstructions: state.clInstructions,
    spectacleDispensing: state.spectacleDispensing,
    doctorReferrals: state.doctorReferrals,
    imagingOrders: state.imagingOrders,
    receptionReferrals: state.receptionReferrals,
    diagnoses: state.diagnoses,
    adviceInstructions: state.adviceInstructions,
    adviceFollowUp: state.adviceFollowUp,
    advicePrecautions: state.advicePrecautions,
    adviceEducation: state.adviceEducation,
    medicalHistorySnapshot: state.medicalHistorySnapshot,
  };
}
